/// Eigene kleine Pixel-Schrift (proportional, 7–8 Pixel hoch), damit auch
/// der Text im Pixelart-Stil bleibt und keine Schriftdatei nötig ist.
abstract final class PixelFont {
  static const int lineHeight = 10;
  static const int spaceWidth = 3;
  static const int _space = 0x20;
  static const int _fallback = 0x3F; // '?'

  /// Zeichencode -> Pixelzeilen ('#' = gesetzt). Die 8. Zeile ist die
  /// Unterlänge (g, j, p, q, y und das Komma).
  static final Map<int, List<String>> glyphs = _parse();

  static Map<int, List<String>> _parse() {
    final out = <int, List<String>>{};
    _source.forEach((key, value) {
      final rows = value.split(' ');
      final width = rows.first.length;
      if (rows.length < 7 || rows.length > 8) {
        throw StateError('Glyphe "$key" hat ${rows.length} Zeilen');
      }
      if (rows.any((r) => r.length != width)) {
        throw StateError('Glyphe "$key" hat ungleich breite Zeilen');
      }
      out[key.codeUnitAt(0)] = rows;
    });
    return out;
  }

  static bool supports(String text) =>
      text.codeUnits.every((c) => c == _space || glyphs.containsKey(c));

  static int advance(int code) {
    if (code == _space) return spaceWidth;
    final g = glyphs[code] ?? glyphs[_fallback]!;
    return g.first.length + 1;
  }

  /// Breite eines Textes in Spielpixeln.
  static int measure(String text) {
    var width = 0;
    for (final c in text.codeUnits) {
      width += advance(c);
    }
    return width > 0 ? width - 1 : 0;
  }

  /// Bricht [text] wortweise auf höchstens [maxWidth] Pixel Breite um.
  static List<String> wrap(String text, int maxWidth) {
    final lines = <String>[];
    for (final paragraph in text.split('\n')) {
      var line = '';
      for (final word in paragraph.split(' ')) {
        final candidate = line.isEmpty ? word : '$line $word';
        if (line.isNotEmpty && measure(candidate) > maxWidth) {
          lines.add(line);
          line = word;
        } else {
          line = candidate;
        }
      }
      lines.add(line);
    }
    return lines;
  }

